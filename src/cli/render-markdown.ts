import type { Report } from '../core/schema.js';

/** GitHub documents a 1 MiB limit per step for job summaries (checked 2026-10-15). */
export const DEFAULT_MARKDOWN_MAX_BYTES = 1_000_000;
const ZWSP = '​';

/**
 * Escapes untrusted text for use as Markdown PROSE: neutralizes formatting, HTML, images,
 * @mentions, #123 references, and auto-links.
 */
export function escapeMarkdown(text: string): string {
  return text
    .replace(/[\\`*_{}[\]<>|~]/g, (c) => `\\${c}`)
    .replace(/^(\s*)([#>+-])/gm, '$1\\$2')
    .replace(/@/g, `@${ZWSP}`)
    .replace(/#(?=\d)/g, `#${ZWSP}`)
    .replace(/\b(https?|ftp):\/\//gi, (_m, scheme: string) => `${scheme}:${ZWSP}//`)
    .replace(/\bwww\./gi, `www${ZWSP}.`)
    .replace(/!\\\[/g, '\\!\\[');
}

/** Wraps text in a code fence that cannot be closed by the content itself. */
export function fence(text: string, info = ''): string {
  let longest = 0;
  for (const m of text.matchAll(/`+/g)) longest = Math.max(longest, m[0].length);
  const marks = '`'.repeat(Math.max(3, longest + 1));
  return `${marks}${info}\n${text}\n${marks}`;
}

export function renderMarkdown(report: Report, options: { maxBytes?: number } = {}): string {
  const maxBytes = options.maxBytes ?? DEFAULT_MARKDOWN_MAX_BYTES;
  const out: string[] = [];
  out.push('## CI failure explanation');
  out.push('');
  const meta: string[] = [`${report.source.format} log`];
  if (report.failedStep) {
    meta.push(
      `failed step: ${escapeMarkdown(report.failedStep)}${report.exitCode !== null ? ` (exit code ${report.exitCode})` : ''}`,
    );
  }
  out.push(meta.join(' · '));
  if (report.truncated) {
    out.push('');
    out.push('> Note: the input was larger than the size limit; only the end of it was analyzed.');
  }
  for (const w of report.warnings) out.push('', `> Warning: ${escapeMarkdown(w)}`);
  out.push('');

  if (report.findings.length === 0) out.push('No error lines found in the log.', '');
  report.findings.forEach((f, i) => {
    const count = f.occurrences > 1 ? ` (${f.occurrences} occurrences)` : '';
    out.push(`### ${i + 1}. ${escapeMarkdown(f.title)}${count}`);
    out.push('');
    out.push(
      `Confidence: **${f.confidence}** · rule: \`${f.ruleId.replace(/`/g, '')}\`${f.step ? ` · step: ${escapeMarkdown(f.step)}` : ''}`,
    );
    out.push('');
    out.push(escapeMarkdown(f.explanation));
    out.push('');
    out.push('Evidence (line numbers refer to the original log):');
    out.push('');
    out.push(fence(f.evidence.map((e) => `${String(e.line).padStart(5)} | ${e.text}`).join('\n')));
    out.push('');
    if (f.suggestions.length > 0) {
      out.push('Suggestions (text only, not executed):');
      out.push('');
      for (const s of f.suggestions) out.push(`- ${escapeMarkdown(s)}`);
      out.push('');
    }
  });

  if (report.llm.used) {
    out.push('### AI explanation');
    out.push('');
    out.push('> AI-generated, may be wrong. Treat as untrusted text.');
    out.push('');
    if (report.llm.summary) out.push(escapeMarkdown(report.llm.summary), '');
  } else if (report.llm.unavailableReason) {
    out.push(`> AI layer unavailable: ${escapeMarkdown(report.llm.unavailableReason)}`, '');
  }
  out.push(
    `<sub>Generated by ci-explain ${escapeMarkdown(report.tool.version)} · ${report.redactions.count} value(s) redacted · suggestions were not executed</sub>`,
  );
  out.push('');

  const text = out.join('\n');
  const bytes = Buffer.byteLength(text, 'utf8');
  if (bytes <= maxBytes) return text;
  const note = '\n\n> Output truncated to fit the size limit.\n';
  // Reserve room for the note and for closing a code fence that the cut may leave open.
  const budget = Math.max(0, maxBytes - Buffer.byteLength(note, 'utf8') - 32);
  let cut = Buffer.from(text, 'utf8').subarray(0, budget).toString('utf8');
  cut = cut.replace(/�$/, '');
  // Never leave an open code fence behind.
  let open: string | null = null;
  for (const line of cut.split('\n')) {
    const m = /^(`{3,})/.exec(line);
    if (!m) continue;
    if (open === null) open = m[1] ?? null;
    else if ((m[1] ?? '').length >= open.length) open = null;
  }
  if (open !== null) cut += `\n${open}`;
  return cut + note;
}
